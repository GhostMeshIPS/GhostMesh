#!/usr/bin/env python3
"""GhostMesh key provisioning (task 15). Spec: PROTOCOL.md §9.1.

    python security/keygen.py                 # nodes A,B,C,D,X + watchtower W
    python security/keygen.py --nodes A,B,C   # fewer boards
    python security/keygen.py --force         # re-key EVERYTHING (reflash every board)

Writes:
  firmware/config/keys/keys_<N>.h   SECRET, one per board (gitignored). Compile in the one for that board.
  firmware/config/keys/keys_W.h     SECRET, watchtower: network key, every pseudo_secret, Ed25519 signing key.
  firmware/config/roster.json       PUBLIC (safe to commit): node IDs, public keys, fingerprints.

Every board prints its own fingerprints at boot (gm_fingerprint); they must match roster.json.
That closes open item O13: a tampered key file or flashing laptop is caught by comparing them.

Keys come only from the OS CSPRNG (secrets.token_bytes). Needs: pip install pynacl
"""
import argparse
import datetime
import hashlib
import json
import secrets
import sys
from pathlib import Path

from nacl.bindings import crypto_scalarmult_base
from nacl.signing import SigningKey

REPO = Path(__file__).resolve().parent.parent
KEYS_DIR = REPO / "firmware" / "config" / "keys"
ROSTER = REPO / "firmware" / "config" / "roster.json"

# Fixed node IDs (real IDs live only inside ciphertext and on the watchtower).
NODE_IDS = {"A": 1, "B": 2, "C": 3, "D": 4, "X": 6}
WATCHTOWER = ("W", 5)
MAX_PEERS = 8      # RT_MAX_PEERS / GM_MAX_PEERS


def fingerprint(key: bytes) -> str:
    """Same as gm_fingerprint(): first 4 bytes of BLAKE2b("GM-FP" || key), as 1a2b-3c4d."""
    h = hashlib.blake2b(b"GM-FP" + key, digest_size=4).hexdigest()
    return f"{h[:4]}-{h[4:]}"


def c_bytes(data: bytes, indent: str = "    ") -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 8]) for i in range(0, len(data), 8)]
    return "{\n" + ",\n".join(indent + r for r in rows) + "\n}"


HEADER_TOP = """/*
 * GENERATED by security/keygen.py on {when}. SECRET: never commit, never share.
 * Board {name} (node ID {nid}). Fingerprints must match firmware/config/roster.json.
 */
#ifndef GHOSTMESH_KEYS_{name}_H
#define GHOSTMESH_KEYS_{name}_H

#include <stdint.h>
"""


def node_header(name, nid, net, ps, sk, wt_pk, peers, when):
    out = [HEADER_TOP.format(when=when, name=name, nid=nid)]
    out.append(f'#define GM_NODE_ID   {nid}u\n#define GM_NODE_NAME "{name}"\n')
    out.append(f"/* fingerprints: self {fingerprint(crypto_scalarmult_base(sk))}, "
               f"network {fingerprint(net)}, watchtower {fingerprint(wt_pk)} */")
    out.append(f"static const uint8_t GM_NETWORK_KEY[32] = {c_bytes(net)};")
    out.append(f"static const uint8_t GM_PSEUDO_SECRET[32] = {c_bytes(ps)};")
    out.append(f"static const uint8_t GM_X25519_SK[32] = {c_bytes(sk)};")
    out.append(f"static const uint8_t GM_WATCHTOWER_PK[32] = {c_bytes(wt_pk)};\n")
    out.append("/* Peers: pass each one to gm_add_peer(). */")
    out.append(f"#define GM_PEER_COUNT {len(peers)}")
    out.append("static const struct { uint32_t id; char name; uint8_t pk[32]; } GM_PEERS[GM_PEER_COUNT] = {")
    for pname, pid, ppk in peers:
        out.append(f"    {{ {pid}u, '{pname}', {c_bytes(ppk, '        ')} }},")
    out.append("};\n\n#endif")
    return "\n".join(out) + "\n"


def watchtower_header(net, wt_seed, wt_pk, nodes, when):
    name, nid = WATCHTOWER
    out = [HEADER_TOP.format(when=when, name=name, nid=nid)]
    out.append(f'#define GM_NODE_ID   {nid}u\n#define GM_NODE_NAME "{name}"\n')
    out.append(f"/* fingerprints: watchtower {fingerprint(wt_pk)}, network {fingerprint(net)} */")
    out.append(f"static const uint8_t GM_NETWORK_KEY[32] = {c_bytes(net)};")
    out.append("/* Monocypher Ed25519 secret key = seed || public key (crypto_ed25519_sign). */")
    out.append(f"static const uint8_t GM_WATCHTOWER_SK[64] = {c_bytes(wt_seed + wt_pk)};")
    out.append(f"static const uint8_t GM_WATCHTOWER_PK[32] = {c_bytes(wt_pk)};\n")
    out.append("/* Every node's pseudonym secret: the watchtower derives pseudonyms + MACs to tag log lines\n"
               " * with \"node\" (decision 1). It holds NO X25519 private keys, so it can't read messages. */")
    out.append(f"#define GM_NODE_COUNT {len(nodes)}")
    out.append("static const struct { uint32_t id; char name; uint8_t pseudo_secret[32]; } GM_NODES[GM_NODE_COUNT] = {")
    for n in nodes:
        out.append(f"    {{ {n['id']}u, '{n['name']}', {c_bytes(n['ps'], '        ')} }},")
    out.append("};\n\n#endif")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--nodes", default="A,B,C,D,X", help="comma-separated board names (default A,B,C,D,X)")
    ap.add_argument("--out", type=Path, default=KEYS_DIR, help="secret headers directory (must be gitignored)")
    ap.add_argument("--roster", type=Path, default=ROSTER, help="public roster JSON path")
    ap.add_argument("--force", action="store_true", help="overwrite existing keys (every board must be reflashed)")
    args = ap.parse_args()

    names = [n.strip().upper() for n in args.nodes.split(",") if n.strip()]
    bad = [n for n in names if n not in NODE_IDS]
    if bad or not names or len(set(names)) != len(names):
        sys.exit(f"--nodes must be distinct names from {sorted(NODE_IDS)}; got {args.nodes!r}")
    if len(names) - 1 > MAX_PEERS:
        sys.exit(f"at most {MAX_PEERS + 1} nodes (each node has at most {MAX_PEERS} peers)")

    existing = list(args.out.glob("keys_*.h")) if args.out.exists() else []
    if existing and not args.force:
        sys.exit(f"{args.out} already has keys ({len(existing)} files). Re-keying means reflashing EVERY board;\n"
                 f"run again with --force if that's what you want.")

    when = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    net = secrets.token_bytes(32)
    wt_seed = secrets.token_bytes(32)
    wt_pk = bytes(SigningKey(wt_seed).verify_key)
    nodes = []
    for n in names:
        sk = secrets.token_bytes(32)
        nodes.append({"name": n, "id": NODE_IDS[n], "ps": secrets.token_bytes(32), "sk": sk,
                      "pk": crypto_scalarmult_base(sk)})

    args.out.mkdir(parents=True, exist_ok=True)
    for old in existing:
        old.unlink()
    for n in nodes:
        peers = [(p["name"], p["id"], p["pk"]) for p in nodes if p is not n]
        (args.out / f"keys_{n['name']}.h").write_text(
            node_header(n["name"], n["id"], net, n["ps"], n["sk"], wt_pk, peers, when), encoding="utf-8")
    (args.out / "keys_W.h").write_text(watchtower_header(net, wt_seed, wt_pk, nodes, when), encoding="utf-8")

    roster = {
        "generated_at": when,
        "note": "PUBLIC. Generated by security/keygen.py. Each board prints these fingerprints at boot; they must match.",
        "network_key_fingerprint": fingerprint(net),
        "watchtower": {"name": WATCHTOWER[0], "id": WATCHTOWER[1], "ed25519_pk": wt_pk.hex(),
                       "fingerprint": fingerprint(wt_pk)},
        "nodes": [{"name": n["name"], "id": n["id"], "role": "attacker (insider)" if n["name"] == "X" else "node",
                   "x25519_pk": n["pk"].hex(), "fingerprint": fingerprint(n["pk"])} for n in nodes],
    }
    args.roster.parent.mkdir(parents=True, exist_ok=True)
    args.roster.write_text(json.dumps(roster, indent=2) + "\n", encoding="utf-8")

    print(f"Wrote {len(nodes) + 1} secret headers to {args.out}")
    print(f"Wrote public roster to {args.roster}\n")
    print(f"  network    {fingerprint(net)}")
    print(f"  W (wt)     {fingerprint(wt_pk)}   Ed25519")
    for n in nodes:
        print(f"  {n['name']} (id {n['id']})   {fingerprint(n['pk'])}   X25519")
    print("\nCompare these with what each board prints at boot.")


if __name__ == "__main__":
    main()
